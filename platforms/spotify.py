"""Spotify via Web API (PKCE, Client ID in SPOTIPY_CLIENT_ID or spotify-client.json).

Uses the development-mode endpoints introduced in February 2026:
/playlists/{id}/items instead of /tracks, POST /me/playlists, search limit of 10.
"""
import json
import os
import re
import secrets

import paths
from matching import gather, queries

from . import signin

NAME = 'spotify'
LABEL = 'Spotify'
SCOPES = 'playlist-read-private playlist-read-collaborative playlist-modify-private playlist-modify-public'
ROOT = paths.data_folder()   # the token lives in the data folder, wherever the program is run from
CLIENT_FILE = ROOT / 'spotify-client.json'      # {"client_id": ...}, written by the set-up page
TOKEN_FILE = ROOT / '.spotify-token'
REDIRECT_URI = 'http://127.0.0.1:8888/callback'
_client = None


def client_id():
    """SPOTIPY_CLIENT_ID if set, else the Client ID saved by the set-up page, else None."""
    if os.environ.get('SPOTIPY_CLIENT_ID'):
        return os.environ['SPOTIPY_CLIENT_ID']
    try:
        return json.loads(CLIENT_FILE.read_text(encoding='utf-8')).get('client_id') or None
    except (OSError, ValueError, AttributeError):
        return None


def owns(url):
    """By host, not by substring: 'soundcloud.com/x/sets/spotify-hits' is not a Spotify link."""
    return bool(re.match(r'(https?://)?([\w-]+\.)*spotify\.com/|spotify:', url.strip(), re.IGNORECASE))


def playlist_key(url):
    """Playlist id: the same for every copy of the link, whatever ?si=... it carries."""
    match = re.search(r'(?:playlist/|playlist:)([A-Za-z0-9]+)', url)
    return match.group(1) if match else url.strip()


def item_id(value):
    """Track id from a track link pasted into match_id; anything else is returned unchanged."""
    match = re.search(r'spotify(?:\.com/(?:[\w-]+/)?track/|:track:)([A-Za-z0-9]+)', value)
    return match.group(1) if match else value


def item_url(item_id):
    return f'https://open.spotify.com/track/{item_id}'


def playlist_url(playlist_id):
    return f'https://open.spotify.com/playlist/{playlist_id}'


def client():
    global _client
    if _client:
        return _client
    import spotipy
    found = client_id()
    if not found:
        raise ValueError('Add your Spotify developer app Client ID on the start page (Services → Set up), '
                         'or set SPOTIPY_CLIENT_ID.')
    _client = spotipy.Spotify(auth_manager=_auth_manager(found))
    return _client


def _auth_manager(found):
    """spotipy's PKCE sign-in with our browser wait (time limit, link on the page) and a new sign-in
    when Spotify has ended the old one. Built here so spotipy is imported only when Spotify is used."""
    from spotipy.exceptions import SpotifyOauthError
    from spotipy.oauth2 import SpotifyPKCE

    class Auth(SpotifyPKCE):
        def get_authorization_code(self, response=None):
            if response:
                return super().get_authorization_code(response)
            state = secrets.token_urlsafe(16)
            return signin.wait_for_code(LABEL, self.get_authorize_url(state=state), REDIRECT_URI, state)

        def validate_token(self, token_info):
            try:
                return super().validate_token(token_info)
            except SpotifyOauthError as error:
                # Refresh tokens end 6 months after signing in; spotipy 2.26 would raise and stay "signed in".
                if getattr(error, 'error', None) != 'invalid_grant':
                    raise
                TOKEN_FILE.unlink(missing_ok=True)
                print('Your Spotify sign-in is no longer valid (Spotify ends it 6 months after signing in): '
                      'sign in again.')
                return None   # spotipy then asks get_authorization_code for a new sign-in

    return Auth(client_id=found, redirect_uri=REDIRECT_URI, scope=SCOPES, cache_path=str(TOKEN_FILE))


def _pages(url, **params):
    page = client()._get(url, **params)
    while page:
        yield from page['items']
        page = client().next(page) if page.get('next') else None


