"""Spotify via Web API (PKCE, Client ID in SPOTIPY_CLIENT_ID).

Uses the development-mode endpoints introduced in February 2026:
/playlists/{id}/items instead of /tracks, POST /me/playlists, search limit of 10.
"""
import os
import re
from pathlib import Path

from matching import gather, queries

NAME = 'spotify'
LABEL = 'Spotify'
SCOPES = 'playlist-read-private playlist-read-collaborative playlist-modify-private playlist-modify-public'
ROOT = Path(__file__).resolve().parent.parent   # the token lives next to the program, wherever it is run from
_client = None


def owns(url):
    """By host, not by substring: 'soundcloud.com/x/sets/spotify-hits' is not a Spotify link."""
    return bool(re.match(r'(https?://)?([\w-]+\.)*spotify\.com/|spotify:', url.strip(), re.IGNORECASE))


def playlist_key(url):
    """Playlist id: the same for every copy of the link, whatever ?si=... it carries."""
    match = re.search(r'(?:playlist/|playlist:)([A-Za-z0-9]+)', url)
    return match.group(1) if match else url.strip()


def item_id(value):
    """Track id from a track link pasted into match_id; anything else is returned unchanged."""
    match = re.search(r'spotify(?:\.com/(?:[\w-]+/)?track/|:track:)([A-Za-z0-9]+)', value)
    return match.group(1) if match else value


def item_url(item_id):
    return f'https://open.spotify.com/track/{item_id}'


def playlist_url(playlist_id):
    return f'https://open.spotify.com/playlist/{playlist_id}'


def client():
    global _client
    if _client:
        return _client
    import spotipy
    from spotipy.oauth2 import SpotifyPKCE
    client_id = os.environ.get('SPOTIPY_CLIENT_ID')
    if not client_id:
        raise ValueError('Set SPOTIPY_CLIENT_ID to your Spotify developer app Client ID.')
    auth = SpotifyPKCE(client_id=client_id, redirect_uri='http://127.0.0.1:8888/callback',
                       scope=SCOPES, cache_path=str(ROOT / '.spotify-token'))
    _client = spotipy.Spotify(auth_manager=auth)
    return _client


def _pages(url, **params):
    page = client()._get(url, **params)
    while page:
        yield from page['items']
        page = client().next(page) if page.get('next') else None


