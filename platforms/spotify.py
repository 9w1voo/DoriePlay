def read_playlist(url):
    """(name, tracks) of a playlist you own or collaborate on."""
    playlist_id = playlist_key(url)
    if not re.fullmatch(r'[A-Za-z0-9]+', playlist_id):
        raise ValueError('Invalid Spotify playlist URL or ID.')
    if playlist_id.startswith('37i9dQZF1'):
        raise ValueError('This playlist is generated by Spotify (Daily Mix, Discover Weekly, Radio...) and the API '
                         'cannot read it. Copy its songs into your own playlist and use that link.')
    from spotipy.exceptions import SpotifyException
    try:
        name = client().playlist(playlist_id, fields='name')['name']
        rows = list(_pages(f'playlists/{playlist_id}/items', limit=50))
    except SpotifyException as error:
        if error.http_status in (403, 404):
            raise ValueError('Spotify only gives access to playlists you own or collaborate on. '
                             'Copy the songs into your own playlist and use that link.') from error
        raise
    tracks = []
    for row in rows:
        item = row.get('item') or row.get('track')
        if not item or item.get('type') != 'track' or row.get('is_local') or item.get('is_local'):
            continue
        tracks.append({'title': item['name'], 'artists': [a['name'] for a in item['artists']],
                       'duration_ms': item['duration_ms'], 'source_id': item['id'],
                       'isrc': (item.get('external_ids') or {}).get('isrc')})
    return name, tracks


