def search(track):
    """Up to 10 candidate tracks per request (the development-mode search limit).
    When the source knows the ISRC (the recording's code), the exact recording is looked up first;
    further, less specific requests are made only while no strong match has been found."""
    def fetch(text):
        items = client().search(q=text, type='track', limit=10)['tracks']['items']
        return [{'id': t['id'], 'title': t['name'], 'artist': ', '.join(a['name'] for a in t['artists']),
                 'seconds': round(t['duration_ms'] / 1000), 'topic': False, 'url': item_url(t['id']),
                 'isrc': (t.get('external_ids') or {}).get('isrc')}
                for t in items if t and t.get('id')]
    exact = [f"isrc:{track['isrc']}"] if track.get('isrc') else []
    return gather(track, exact + queries(track), fetch)


def create_playlist(name):
    result = client()._post('me/playlists', payload={
        'name': name, 'public': False, 'description': 'Transferred with Dorie Play'})
    return result['id']


def playlist_counts(playlist_id):
    existing = {}
    for row in _pages(f'playlists/{playlist_id}/items', limit=50):
        item = row.get('item') or row.get('track')
        if item and item.get('id'):
            existing[item['id']] = existing.get(item['id'], 0) + 1
    return existing


def add_items(playlist_id, items):
    """items: list of (track_id, label). Added in batches of 100, order kept.
    Returns [(label, reason)] for ids Spotify does not accept; the other songs are still added."""
    from spotipy.exceptions import SpotifyException
    skipped, valid = [], []
    for track_id, label in items:
        if re.fullmatch(r'[A-Za-z0-9]{22}', track_id):
            valid.append((track_id, label))
        else:
            skipped.append((label, f'"{track_id}" is not a Spotify track id'))

    def post(batch):
        client()._post(f'playlists/{playlist_id}/items',
                       payload={'uris': [f'spotify:track:{track_id}' for track_id, _ in batch]})

    for start in range(0, len(valid), 100):
        batch = valid[start:start + 100]
        try:
            post(batch)
            added = batch
        except SpotifyException as error:
            if error.http_status != 400:
                raise
            added = []   # one bad id rejects the whole batch: add one by one to find it
            for entry in batch:
                try:
                    post([entry])
                    added.append(entry)
                except SpotifyException as single:
                    if single.http_status != 400:
                        raise
                    skipped.append((entry[1], f'Spotify rejected id {entry[0]}'))
        for _, label in added:
            print('Added:', label)
    return skipped
